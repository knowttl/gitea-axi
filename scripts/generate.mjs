import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { command, commands, limits } from '../src/registry.ts';
import { encode } from '@toon-format/toon';

const check = process.argv.slice(2);
assert(check.length === 0 || (check.length === 1 && check[0] === '--check'), 'Use --check or no arguments');
const root = new URL('../', import.meta.url);
const swagger = JSON.parse(await readFile(new URL('evidence/docs/gitea-1.23.4-swagger.json', root), 'utf8'));
const fields = { Repository: ['id', 'full_name', 'default_branch'], ServerVersion: ['version'] };
const schemas = {};
let types = '// Generated by scripts/generate.mjs from the retained Swagger; do not edit.\n';
for (const [name, keys] of Object.entries(fields)) {
  const properties = Object.fromEntries(keys.map(key => {
    const property = swagger.definitions[name].properties[key];
    assert(['string', 'integer'].includes(property.type), `Unsupported vendor field ${name}.${key}`);
    return [key, { type: property.type }];
  }));
  schemas[name] = { type: 'object', properties, required: keys, additionalProperties: true };
  types += `export interface ${name} {\n${keys.map(key => `  ${key}: ${properties[key].type === 'integer' ? 'number' : 'string'};`).join('\n')}\n}\n`;
}
const routes = {
  version: swagger.basePath + '/version',
  repository: swagger.basePath + '/repos/{owner}/{repo}',
  specification: '/swagger.v1.json',
};
assert.equal(swagger.paths['/version'].get.operationId, 'getVersion');
assert.equal(swagger.paths['/repos/{owner}/{repo}'].get.operationId, 'repoGet');
types += `export const routes = ${JSON.stringify(routes, null, 2)} as const;\n`;
schemas.Specification = {
  type: 'object', required: ['info', 'paths'], additionalProperties: true,
  properties: {
    info: {
      type: 'object', required: ['version'], additionalProperties: true,
      properties: { version: { type: 'string' } },
    },
    paths: { type: 'object', minProperties: 1, additionalProperties: { type: 'object' } },
  },
};
const help = encode({
  command: 'gitea-axi ' + command.path.join(' '),
  description: command.description,
  flags: Object.entries(command.flags).map(([flag, meta]) => ({
    flag: '--' + flag, type: meta.type,
    requirement: 'required' in meta ? 'required' : `default ${meta.default}`,
    description: meta.description,
  })),
  limits,
  examples: [...command.examples],
}) + '\n';
const artifacts = {
  'src/vendor.generated.ts': types,
  'schemas/responses.json': JSON.stringify(schemas, null, 2) + '\n',
  'generated/help.txt': help,
  'generated/host-inventory.json': JSON.stringify({
    schemaVersion: 1, tool: 'gitea-axi', commands, limits,
  }, null, 2) + '\n',
  'schemas/vendor.json': JSON.stringify({ definitions: swagger.definitions }, null, 2) + '\n',
  'generated/routes.json': JSON.stringify(Object.entries(swagger.paths).flatMap(([path, methods]) => methods.get ? [{
    path: swagger.basePath + path, operation: methods.get.operationId,
    effect: /registration-token|\/tokens(?:\/|$)|signing-key/.test(path) ? 'credential' : 'read',
    schema: (methods.get.responses?.['200']?.$ref ? swagger.responses[methods.get.responses['200'].$ref.split('/').at(-1)] : methods.get.responses?.['200'])?.schema ?? null,
  }] : []), null, 2) + '\n',
};
for (const [path, content] of Object.entries(artifacts)) {
  const target = new URL(path, root);
  if (check.length) {
    assert.equal(await readFile(target, 'utf8'), content, `Stale generated artifact: ${path}; run npm run generate`);
  } else {
    await mkdir(new URL('.', target), { recursive: true });
    await writeFile(target, content);
  }
}
